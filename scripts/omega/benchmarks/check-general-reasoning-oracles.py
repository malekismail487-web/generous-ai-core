"""Independent development-fixture cross-check; never loads GPQA or model output.

Input is generated by generalReasoningTasks.ts, exclusively from repository-owned
procedural fixtures. No model-generated code is accepted here. Different language
and fixed-point/Decimal/actual Python semantics reduce, not eliminate, correlation.
"""
import json
import re
import sys
from decimal import Decimal, ROUND_HALF_UP


def number(text):
    return Decimal(text)


def rounded(value):
    return str(value.quantize(Decimal("0.001"), rounding=ROUND_HALF_UP))


def expected(task):
    question = task["question"]
    if task["domain"] == "BAYES":
        values = re.findall(r"(\d+)%", question.split("\nChoose exactly", 1)[0])
        assert len(values) == 5
        prior, s1, f1, s2, f2 = [number(x) / 100 for x in values]
        # Normalize posterior odds, rather than using the generator's integer weights.
        odds = prior / (1 - prior) * s1 / f1 * (1 - s2) / (1 - f2)
        return rounded(100 * odds / (1 + odds)) + "%"
    if task["domain"] == "CAUSAL":
        high, low = map(number, re.search(r"has (\d+) high-baseline and (\d+) low-baseline", question).groups())
        ah, bh, al, bl = map(number, re.findall(r"(?:high/A|high/B|low/A|low/B) (\d+)%", question))
        # Compute expected successes under two separate population interventions.
        successes_a = high * ah / 100 + low * al / 100
        successes_b = high * bh / 100 + low * bl / 100
        return "Intervention A minus intervention B: " + rounded(100 * (successes_a - successes_b) / (high + low)) + " percentage points"
    if task["domain"] == "SYMMETRY":
        n, k = map(int, re.search(r"has (\d+) binary positions with exactly (\d+) ones", question).groups())
        # Burnside: average fixed configurations across group elements, no canonical strings.
        valid = []
        for mask in range(1 << n):
            if mask.bit_count() != k:
                continue
            shifted = ((mask << 1) | (mask >> (n - 1))) & ((1 << n) - 1)
            if mask & shifted == 0:
                valid.append(mask)
        fixed = 0
        for shift in range(n):
            for mask in valid:
                rotated = ((mask << shift) | (mask >> (n - shift))) & ((1 << n) - 1)
                fixed += rotated == mask
        assert fixed % n == 0
        return str(fixed // n)
    if task["domain"] == "PROGRAM_STATE":
        code = question.split("\n\n", 1)[1].split("\nChoose exactly", 1)[0]
        # Exact allowlist for trusted fixture code before actual Python execution.
        pattern = (r"x = \[[0-9, ]+\]\ny = x\nz = x\[:\]\nfor i in range\([5-7]\):\n"
                   r"    y.append\(z\[i % 4\] \+ x\[i\]\)\n    if i % 2 == 0:\n"
                   r"        z\[i % 4\] = y\[-1\] - z\[\(i \+ 1\) % 4\]\n"
                   r"    x\[\(i \+ 1\) % len\(x\)\] = z\[i % 4\] \+ y\[i\]\nprint\(sum\(x\) \+ 2 \* sum\(z\)\)")
        assert re.fullmatch(pattern, code), "unrecognized development code"
        outputs = []
        exec(compile(code, "trusted-development-fixture", "exec"), {"__builtins__": {},
             "range": range, "sum": sum, "len": len, "print": outputs.append})
        assert len(outputs) == 1
        return str(outputs[0])
    raise AssertionError("unknown domain")


tasks = json.load(sys.stdin)
assert len(tasks) == 12 and len({t["taskId"] for t in tasks}) == 12
for task in tasks:
    options = re.findall(r"^[1-4]\. (.+)$", task["question"], flags=re.MULTILINE)
    assert len(options) == 4 and len(set(options)) == 4
    assert options[int(task["answer"]) - 1] == expected(task), task["taskId"]
print(json.dumps({"verifiedProceduralOracles": len(tasks), "domains": 4,
                  "officialBenchmark": False, "rawQuestionOrAnswerOutput": False}))
